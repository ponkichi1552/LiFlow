import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = new URL('../', import.meta.url);
const snapshot = JSON.parse(readFileSync(new URL('docs/catalog/household-care-2026-11-01.json', root), 'utf8'));
const original = readFileSync(new URL('docs/catalog/household-care-source-2026-11-01.txt', root));
if (createHash('sha256').update(original).digest('hex') !== snapshot.sourceSha256) throw new Error('The document snapshot changed. Review its contents and provenance before generating.');
const minutes = [20, 35, 25, 10, 15, 20, 45, 10, 20, 30, 25, 15, 10, 30, 15, 10, 15, 20, 20, 10, 15, 10, 15, 10, 10, 10, 10, 15, 20, 25, 35, 10, 10, 10, 10, 15];
if (snapshot.items.length !== 36 || snapshot.items.some((item, index) => item.number !== index + 1 || item.estimatedMinutes !== minutes[index])) throw new Error('Expected the user-provided 36-item working-time table.');
const content = snapshot.items.map(({ documentMinutes: _excludedElapsedTime, ...item }) => item);
const source = `// Generated by scripts/generate-household-care-guide.mjs. Edit the reviewed source snapshot, then regenerate.
// Descriptions and cadence come from the supplied document; minutes come exclusively from the user's table.
export interface HouseholdCareGuideEntry {
  number: number;
  name: string;
  category: string;
  description: string;
  tools: string;
  instructions: string[];
  cautions: string;
  trivia: string;
  conditions: string;
  frequency: string;
  estimatedMinutes: number;
  frequencyEvidence: string;
  sourceUrl: string;
}
export const HOUSEHOLD_CARE_SOURCE_URL = ${JSON.stringify(snapshot.documentUrl)};
export const HOUSEHOLD_CARE_GUIDE: readonly HouseholdCareGuideEntry[] = ${JSON.stringify(content, null, 2)};
`;
const target = new URL('src/domain/chores/household-care-guide.ts', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== source) throw new Error('The bundled guide differs from the reviewed source snapshot.');
} else writeFileSync(target, source);
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} 36 guide entries and table-sourced working times: ${fileURLToPath(target)}`);
